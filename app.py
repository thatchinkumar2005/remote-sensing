"""
app.py - Streamlit interface for the Remote Sensing demo.
Run with:   streamlit run app.py
The image-processing code is in rs_core.py, the figures are in plots.py.
"""
from pathlib import Path

import numpy as np
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt

import plots
import rs_core as rs

DATA_FILE = Path(__file__).parent / "data" / "scene.npz"
REAL = "Real Sentinel-2 crop (data/scene.npz)"
SYNTH = "Synthetic demo scene (NOT real data)"

st.set_page_config(page_title="Remote Sensing Demo", layout="wide")


def show(fig):
    st.pyplot(fig, clear_figure=True)
    plt.close(fig)


@st.cache_data(show_spinner="Loading scene ...")
def get_scene(source, file_mtime):
    # file_mtime is only here so the cache refreshes if you download new data
    return rs.load_scene(DATA_FILE) if source == REAL else rs.make_synthetic_scene()


# ---------------------------------------------------------------- sidebar
st.sidebar.title("Remote Sensing Demo")
real_available = DATA_FILE.exists()
options = [REAL, SYNTH] if real_available else [SYNTH]
source = st.sidebar.radio("Data source", options)
if not real_available:
    st.sidebar.warning("data/scene.npz not found. Run  python download_data.py  once to get REAL data. "
                       "Until then only the synthetic scene is available.")

scene = get_scene(source, DATA_FILE.stat().st_mtime if real_available else 0)
meta = scene["meta"]
H, W = scene["refl"]["red"].shape

with st.sidebar.expander("Dataset information", expanded=True):
    st.markdown("**%s**" % meta["title"])
    st.markdown("- Source: %s" % meta["source"])
    st.markdown("- Sensor: %s" % meta["sensor"])
    st.markdown("- Acquired: %s" % meta["datetime"])
    st.markdown("- Cloud cover (whole scene): %s" % meta["cloud_cover"])
    st.markdown("- Pixel size: %s m" % meta["pixel_size_m"])
    st.markdown("- Licence: %s" % meta["license"])
    if meta.get("item_id"):
        st.markdown("- Scene ID: `%s`" % meta["item_id"])

# ---------------------------------------------------------------- header
st.title("Remote Sensing with Python: bands, composites, contrast and NDVI")
if meta["is_real"]:
    st.success("REAL DATA: genuine Sentinel-2 satellite measurements (blue, green, red and near-infrared bands).")
else:
    st.warning("SYNTHETIC DATA: this image was generated by a program. It is NOT a satellite image. "
               "It is used only because its true values are known, which makes NDVI easy to check by hand.")

tab1, tab2, tab3 = st.tabs(["Module 1 - Data, bands and resolution",
                            "Module 2 - Composites and contrast",
                            "Module 3 - NDVI and vegetation"])

# ================================================================= MODULE 1
with tab1:
    st.header("Module 1: What does a satellite image contain?")
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Image size (rows x columns)", "%d x %d" % (H, W))
    c2.metric("Spectral bands loaded", "4 (B, G, R, NIR)")
    c3.metric("Pixel size on the ground", "%s m" % meta["pixel_size_m"])
    c4.metric("Area covered", "%.1f km x %.1f km" % (H * meta["pixel_size_m"] / 1000, W * meta["pixel_size_m"] / 1000))
    st.caption("A pixel size of 10 m means each pixel represents a 10 m x 10 m square of ground.")

    st.subheader("1.1 Where our bands sit in the electromagnetic spectrum")
    show(plots.fig_em_spectrum())

    st.subheader("1.2 One image per band")
    st.caption("Each band is a separate grey-scale image (a 2-D array of numbers). "
               "Bright = high reflectance in that band. Each is displayed with a 2-98% contrast stretch.")
    show(plots.fig_four_bands(scene))

    st.subheader("1.3 Zoom into the numbers: an image is an array")
    cc1, cc2 = st.columns([1, 1.3])
    with cc1:
        band = st.selectbox("Band", list(rs.BANDS), index=2, key="zoom_band_" + source,
                            format_func=lambda b: "%s (%s)" % (rs.BAND_TABLE[b]["label"], rs.BAND_TABLE[b]["s2"]))
        row = st.slider("Top-left row", 0, H - 8, H // 2, key="zoom_row_" + source)
        col = st.slider("Top-left column", 0, W - 8, W // 2, key="zoom_col_" + source)
        show(plots.fig_band_with_window(scene, band, row, col))
    with cc2:
        dn_win, r0, c0 = rs.pixel_window(scene["dn"][band], row, col)
        rf_win, _, _ = rs.pixel_window(scene["refl"][band], row, col)
        idx = ["row %d" % (r0 + i) for i in range(8)]
        cols = ["col %d" % (c0 + j) for j in range(8)]
        st.markdown("**Digital numbers (DN)** - integers stored in the file (`uint16`)")
        st.dataframe(pd.DataFrame(dn_win, index=idx, columns=cols))
        st.markdown("**Surface reflectance** = DN x %g + (%g)  (0 = no light reflected, 1 = all reflected)"
                    % (meta["scale"], meta["offset"]))
        st.dataframe(pd.DataFrame(rf_win, index=idx, columns=cols).round(4))

    st.subheader("1.4 Resolution: spatial and radiometric")
    r1, r2 = st.columns(2)
    factor = r1.select_slider("Spatial resolution: make pixels this many times larger", [1, 2, 4, 8, 16, 32], 1,
                              key="factor_" + source)
    bits = r2.slider("Radiometric resolution: bits per pixel", 1, 8, 8, key="bits_" + source)
    show(plots.fig_resolution(scene, factor, bits))
    st.caption("Spatial resolution = size of one pixel on the ground. Radiometric resolution = number of brightness "
               "levels (2^bits). Spectral resolution = number and width of bands (fixed here: 4 bands). "
               "Temporal resolution = how often the satellite revisits (Sentinel-2: every 5 days with two satellites).")

# ================================================================= MODULE 2
with tab2:
    st.header("Module 2: Colour composites, histograms and contrast enhancement")
    k1, k2 = st.columns(2)
    kind = k1.radio("Composite", list(rs.COMPOSITES), key="kind_" + source)
    method = k2.selectbox("Enhancement", rs.ENHANCEMENTS, index=2, key="method_" + source)
    low, high, gamma = 2.0, 98.0, 0.6
    if method == rs.ENHANCEMENTS[2]:
        low, high = st.slider("Percentile range (pixels outside are clipped to black / white)", 0.0, 100.0,
                              (2.0, 98.0), 0.5, key="pct_" + source)
        high = max(high, low + 0.5)          # keep the range valid if both handles meet
    if method == rs.ENHANCEMENTS[3]:
        gamma = st.slider("Gamma (below 1 = brighter, above 1 = darker)", 0.2, 3.0, 0.6, 0.05, key="gamma_" + source)

    chans = rs.raw_channels(scene, kind)
    raw_img, _ = rs.make_composite(chans, rs.ENHANCEMENTS[0])
    enh_img, enh_chs = rs.make_composite(chans, method, low, high, gamma)
    names = rs.COMPOSITES[kind]
    show(plots.fig_composites(raw_img, enh_img, kind, method))
    if kind.startswith("True"):
        st.caption("True colour: red band -> red channel, green band -> green channel, blue band -> blue channel. "
                   "Looks like a photograph.")
    else:
        st.caption("False colour: NIR band -> red channel, red band -> green channel, green band -> blue channel. "
                   "Healthy vegetation reflects a lot of NIR, so it appears bright red.")

    st.subheader("Histograms of the three display channels")
    show(plots.fig_histograms(chans, enh_chs, ["%s band -> displayed as %s" % (n, c)
                                                for n, c in zip(names, ["red", "green", "blue"])]))
    rows = []
    for n, raw, enh in zip(names, chans, enh_chs):
        m = np.isfinite(raw)
        rows.append({"Channel (band)": n,
                     "Before: min": round(float(raw[m].min()), 3), "Before: max": round(float(raw[m].max()), 3),
                     "Before: std dev": round(float(raw[m].std()), 3),
                     "After: min": round(float(enh[m].min()), 3), "After: max": round(float(enh[m].max()), 3),
                     "After: std dev": round(float(enh[m].std()), 3)})
    st.dataframe(pd.DataFrame(rows), hide_index=True)
    st.caption("Raw reflectance occupies only a small part of 0-1, so the image looks dark and flat. "
               "A stretch spreads the values over the full display range (larger std dev = more contrast). "
               "Enhancement changes only how the image LOOKS; it does not change the measured reflectance used for NDVI.")

# ================================================================= MODULE 3
with tab3:
    st.header("Module 3: Vegetation and NDVI")
    ndvi = rs.compute_ndvi(scene["refl"]["nir"], scene["refl"]["red"])
    picks = rs.quick_picks(scene, ndvi)

    st.subheader("3.1 Choose a pixel to inspect")
    manual = "Manual (use the sliders)"
    choice = st.selectbox("Example pixel", list(picks) + [manual], key="pick_" + source)
    if choice == manual:
        m1, m2 = st.columns(2)
        row = m1.slider("Row", 0, H - 1, H // 2, key="prow_" + source)
        col = m2.slider("Column", 0, W - 1, W // 2, key="pcol_" + source)
    else:
        row, col = picks[choice]
        st.caption("Selected pixel: row %d, column %d" % (row, col))

    st.subheader("3.2 NDVI map next to the false-colour composite")
    stretch_scale = st.checkbox("Stretch the NDVI colour scale to the data (2-98 percentile) - a contrast stretch for the NDVI map",
                                value=False, key="nstretch_" + source)
    false_img, _ = rs.make_composite(rs.raw_channels(scene, "False colour (NIR, R, G)"), rs.ENHANCEMENTS[2])
    show(plots.fig_ndvi_vs_falsecolour(false_img, ndvi, row, col, stretch_scale))
    st.caption("The ring marks the selected pixel. Green = high NDVI (vegetation), yellow/orange = low, "
               "red = negative (water, shadow, clouds). Compare with the red areas in the false-colour image.")

    st.subheader("3.3 Spectral signature and NDVI calculated by hand")
    s1, s2 = st.columns([1.15, 1])
    with s1:
        show(plots.fig_spectra(scene, picks, choice if choice != manual else None))
    with s2:
        b, g, r_, n_ = rs.pixel_values(scene, row, col)
        st.markdown("**Values at row %d, column %d**" % (row, col))
        st.dataframe(pd.DataFrame({"Band": ["Blue", "Green", "Red", "NIR"],
                                   "Reflectance": [round(v, 4) for v in (b, g, r_, n_)]}),
                     hide_index=True)
        if np.isfinite(n_) and np.isfinite(r_) and (n_ + r_) != 0:
            val = (n_ - r_) / (n_ + r_)
            st.latex(r"NDVI=\frac{NIR-Red}{NIR+Red}=\frac{%.4f-%.4f}{%.4f+%.4f}=\frac{%.4f}{%.4f}=%.3f"
                     % (n_, r_, n_, r_, n_ - r_, n_ + r_, val))
            st.metric("NDVI at this pixel", "%.3f" % val)
            if val < 0:
                st.info("Negative: typical of water (it absorbs NIR), or clouds/shadow.")
            elif val < 0.2:
                st.info("Low: bare soil, rock, sand or built-up surface.")
            elif val < 0.5:
                st.info("Moderate: sparse, young or stressed vegetation.")
            else:
                st.info("High: dense, healthy, actively photosynthesising vegetation.")
        else:
            st.error("No valid data at this pixel (NDVI undefined).")

    st.subheader("3.4 Interpreting NDVI: classes and histogram")
    cls, pct = rs.classify_ndvi(ndvi)
    d1, d2 = st.columns(2)
    with d1:
        show(plots.fig_classes(cls, pct))
    with d2:
        show(plots.fig_ndvi_hist(ndvi))
    st.caption("The thresholds (0, 0.2, 0.5) are common rules of thumb, not laws. The best values depend on the sensor, "
               "season, crop and soil, so interpret them with local knowledge.")
